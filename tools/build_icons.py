def build():
    symbols = {}
    for key, (d, name) in ICONS.items():
        symbols.setdefault(name, d)
    symbols.update(EXTRA)
    body = "\n".join(
        f'<symbol id="{name}" viewBox="0 0 24 24"><path d="{d}" fill="none" stroke="currentColor" '
        f'stroke-width="{3 if name == "dots-three" else 2}" stroke-linecap="round" stroke-linejoin="round"/></symbol>' for name, d in sorted(symbols.items()))
    out = ('<svg xmlns="http://www.w3.org/2000/svg">\n'
           '<!-- Mockup icons. Each id is the Phosphor 2.0 icon name. Generated by tools/build_icons.py -->\n'
           f'{body}\n</svg>\n')
    path = Path(__file__).resolve().parent.parent / "docs/assets/icons.svg"
    path.write_text(out, encoding="utf-8")
    print(f"Wrote {path} ({len(symbols)} icons)")


if __name__ == "__main__":
    build()
